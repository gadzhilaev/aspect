def opening_for_assessment(state: AssessmentState | str) -> str:
    if state == "finance_data_required":
        return OPENING_FINANCE_REQUIRED
    if state == "finance_ready":
        return OPENING_FINANCE_READY
    if state == "monitoring_only":
        return OPENING_MONITORING
    if state == "calculation_unavailable":
        return OPENING_CALCULATION_UNAVAILABLE
    return OPENING_MESSAGE


def chips_for_assessment(state: AssessmentState | str) -> list[str]:
    if state == "finance_data_required":
        return list(SUGGESTION_CHIPS_FINANCE_REQUIRED)
    if state == "finance_ready":
        return list(SUGGESTION_CHIPS_FINANCE_READY)
    if state == "monitoring_only":
        return list(SUGGESTION_CHIPS_MONITORING)
    if state == "calculation_unavailable":
        return list(SUGGESTION_CHIPS_CALCULATION_UNAVAILABLE)
    return list(SUGGESTION_CHIPS)
